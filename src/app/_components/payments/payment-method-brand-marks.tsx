interface PlaceholderMarkProps {
  size?: number
  /** Обычно первая буква названия метода (H / R / C и т.д.) */
  letter: string
  /** CSS-переменная цвета, например 'var(--heleket)' */
  colorVar: string
}

/**
 * Заготовка под ещё не добавленную иконку способа оплаты.
 * Пунктирная рамка — явный сигнал "сюда нужна настоящая иконка",
 * чтобы не перепутать с финальным дизайном.
 */
export function PlaceholderMark({
  size = 16,
  letter,
  colorVar,
}: PlaceholderMarkProps) {
  return (
    <div
      style={{
        width: size + 4,
        height: size + 4,
        borderRadius: '9999px',
        border: `1.5px dashed ${colorVar}`,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        color: colorVar,
        fontSize: size * 0.55,
        fontWeight: 700,
        fontFamily: 'monospace',
        lineHeight: 1,
        opacity: 0.85,
        flexShrink: 0,
      }}
      title="TODO: заменить на реальную иконку метода">
      {letter}
    </div>
  )
}
